// Usage: node tools/gen-unicode-case-table.js
// The checked-in Unicode 17.0.0 data makes regeneration independent of Node's ICU version.
const fs = require("node:fs");
const path = require("node:path");
const { createHash } = require("node:crypto");

const dataDir = path.join(__dirname, "unicode-17.0.0");
const folds = [];
const properties = { Uppercase: [], Lowercase: [], Titlecase: [] };
const sources = ["CaseFolding.txt", "DerivedCoreProperties.txt", "UnicodeData.txt"];
const inputs = sources.map((name) => fs.readFileSync(path.join(dataDir, name), "utf8"));

for (const line of inputs[0].split(/\r?\n/)) {
  const [code, status, mapping] = line
    .split("#")[0]
    .split(";")
    .map((part) => part.trim());
  if (status !== "C" && status !== "S") continue;
  const mapped = mapping.split(/\s+/);
  if (mapped.length !== 1) throw new Error(`Simple fold expands: ${line}`);
  folds.push([parseInt(code, 16), parseInt(mapped[0], 16)]);
}

for (const line of inputs[1].split(/\r?\n/)) {
  const [range, property] = line
    .split("#")[0]
    .split(";")
    .map((part) => part.trim());
  if (property !== "Uppercase" && property !== "Lowercase") continue;
  const [start, end = start] = range.split("..");
  properties[property].push([parseInt(start, 16), parseInt(end, 16)]);
}

for (const line of inputs[2].split(/\r?\n/)) {
  const [code, , category] = line.split(";");
  if (category === "Lt") properties.Titlecase.push([parseInt(code, 16), parseInt(code, 16)]);
}

function mergeRanges(ranges) {
  const merged = [];
  for (const [start, end] of ranges.sort((a, b) => a[0] - b[0])) {
    const last = merged.at(-1);
    if (last && start <= last[1] + 1) last[1] = Math.max(last[1], end);
    else merged.push([start, end]);
  }
  return merged;
}

const hex = (value) => "0x" + value.toString(16).toUpperCase().padStart(4, "0");
let output = "// AUTO-GENERATED by tools/gen-unicode-case-table.js.\n";
output += "// Unicode 17.0.0 simple case folding (C + S), excluding locale-specific T mappings.\n";
output += "// Source: https://www.unicode.org/Public/17.0.0/ucd/\n";
output += "// Copyright Unicode, Inc. Distributed under LICENSE-Unicode.\n";
for (let i = 0; i < sources.length; i++) {
  output += `// ${sources[i]} SHA-256: ${createHash("sha256").update(inputs[i]).digest("hex")}\n`;
}
output += "#pragma once\n\n";
output += "struct UnicodeCaseFold { char32_t codepoint; char32_t folded; };\n";
output += "struct UnicodePropertyRange { char32_t start; char32_t end; };\n\n";
output += "inline constexpr UnicodeCaseFold kUnicodeCaseFolds[] = {\n";
for (const [code, mapping] of folds.sort((a, b) => a[0] - b[0])) {
  output += `  {${hex(code)}, ${hex(mapping)}},\n`;
}
output += "};\n";
for (const [name, ranges] of Object.entries(properties)) {
  output += `\ninline constexpr UnicodePropertyRange kUnicode${name}Ranges[] = {\n`;
  for (const [start, end] of mergeRanges(ranges)) output += `  {${hex(start)}, ${hex(end)}},\n`;
  output += "};\n";
}
fs.writeFileSync(path.join(__dirname, "..", "src", "unicode_case_table.h"), output);
console.log(`Generated ${folds.length} Unicode simple case folds.`);
